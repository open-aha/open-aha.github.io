// Writes js/courses/catalog.js: what the home and course pages need, without lesson steps.
// The app loads a course's full file (js/courses/<id>.js) only when one of its lessons opens.
// scripts/validate.mjs calls this, so running the validator keeps the catalog up to date.
// Usage: node scripts/build-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { courses } from '../js/courses/index.js';

const OUT = new URL('../js/courses/catalog.js', import.meta.url);

export function catalogSource() {
  const meta = courses.map(({ chapters, ...c }) => ({
    ...Object.fromEntries(Object.entries(c).filter(([, v]) => typeof v !== 'function')),
    chapters: chapters.map((ch) => ({
      title: ch.title,
      summary: ch.summary,
      lessons: ch.lessons.map((l) => ({
        id: l.id,
        title: l.title,
        summary: l.summary,
        icon: l.icon,
        nSteps: l.steps.length,
        minutes: l.minutes || Math.max(5, Math.round(l.steps.length * 0.9)),
      })),
    })),
  }));
  return `// Generated by scripts/build-catalog.mjs from js/courses/index.js. Do not edit by hand.
// Lesson steps are left out; nSteps is the step count. Full courses load on demand.
export const courses = ${JSON.stringify(meta, null, 1)};
`;
}

// rewrites the catalog if it differs; returns true when it changed
export function updateCatalog() {
  const src = catalogSource();
  let cur = '';
  try {
    cur = readFileSync(OUT, 'utf8');
  } catch (e) {
    /* missing */
  }
  if (cur === src) return false;
  writeFileSync(OUT, src);
  return true;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(updateCatalog() ? 'updated js/courses/catalog.js' : 'js/courses/catalog.js is up to date');
}
